    def _get_turn_A(self, omega):
        """根据转向角计算转弯模型的状态转移矩阵"""
        dtheta = math.pi / 180 * omega   # 角速度（转向角/时间步长）
        theta = dtheta * self.dt
        return np.array([
            [1.0, math.sin(theta)/dtheta, 0.0, -
             (1 - math.cos(theta))/dtheta, 0.0],
            [0.0, math.cos(theta), 0.0, -math.sin(theta), 0.0],
            [0.0, (1 - math.cos(theta))/dtheta, 1.0,
             math.sin(theta)/dtheta, 0.0],
            [0.0, math.sin(theta), 0.0, math.cos(theta), 0.0],
            [0., 0., 0., 0., 1.]
        ])

    def get_model_params(self, intention):
        """根据意图获取对应的模型参数（自动处理越界情况）"""
        intention = max(0, min(intention, 2))  # 确保意图在0-2范围内
        return self.model_params[intention]

